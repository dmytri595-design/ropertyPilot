(async()=>{
const {chromium}=require('playwright');
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({acceptDownloads:true,viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',e=>errors.push(String(e)));
await page.goto(process.env.SMOKE_URL||'http://127.0.0.1:4173',{waitUntil:'domcontentloaded'});
await page.waitForSelector('.app-shell');
if(!(await page.locator('body').innerText()).includes('Good morning, Jordan'))throw new Error('Dashboard did not load');
await page.locator('a[href="#templates"]').click();
await page.waitForSelector('.template-card');
await page.locator('.template-card').filter({hasText:'Rental'}).click();
let state=await page.evaluate(()=>JSON.parse(localStorage.getItem('propertypilot:v1')));
if(state.template!=='rental')throw new Error('Selected template was not saved');
await page.locator('a[href="#new"]').click();
await page.getByRole('button',{name:'Load fictional sample'}).click();
if(await page.locator('#new-form [name="listingPurpose"]').inputValue()!=='For Rent')throw new Error('Sample listing purpose did not load');
if(await page.locator('#new-form [name="currency"]').inputValue()!=='NOK')throw new Error('Sample currency did not load');
if(await page.locator('#photo-grid .photo-card').count()!==2)throw new Error('Fictional sample photos did not load');
await page.locator('#new-form button[type="submit"]').click();
await page.waitForURL(/#property\/PROP-1006/);
await page.waitForSelector('#content-description .content-text');
const description=await page.locator('#content-description .content-text').innerText();
const seo=await page.locator('#content-seo .content-text').innerText();
const instagram=await page.locator('#content-instagram').innerText();
if(!description.includes('rental-ready')||!description.toLowerCase().includes('for rent'))throw new Error('Selected template/listing purpose did not affect the description');
if(!seo.includes('for Rent'))throw new Error('SEO copy does not reflect the rental purpose');
if(!instagram.includes('#PropertyForRent'))throw new Error('Social hashtags do not reflect the rental purpose');
await page.getByRole('button',{name:'Mark as Published'}).click();
if(!(await page.locator('.head-actions').innerText()).includes('Published'))throw new Error('Local publish status failed');
await page.getByRole('button',{name:'Archive',exact:true}).click();
if(!(await page.locator('.head-actions').innerText()).includes('Archived'))throw new Error('Archive status failed');
await page.getByRole('button',{name:'Restore to Draft'}).click();
if(!(await page.locator('.head-actions').innerText()).includes('Draft'))throw new Error('Restore to Draft failed');
await page.locator('.head-actions').getByRole('button',{name:'Generate Marketing Package'}).click();
await page.waitForSelector('#modal-root .gen-modal',{state:'visible'});
await page.waitForSelector('#modal-root .gen-modal',{state:'detached',timeout:10000});
if(!(await page.locator('.head-actions').innerText()).includes('Ready'))throw new Error('Generate workflow did not set Ready status');
const textExportPromise=page.waitForEvent('download');
await page.locator('#content-seo').getByRole('button',{name:'Export'}).click();
const txt=await textExportPromise;
if(!txt.suggestedFilename().endsWith('.txt'))throw new Error('Single-content export failed');
const jsonExportPromise=page.waitForEvent('download');
await page.locator('.topbar').getByRole('button',{name:'Export'}).click();
const json=await jsonExportPromise;
if(!json.suggestedFilename().endsWith('.json'))throw new Error('Workspace JSON export failed');
await page.locator('a[href="#settings"]').click();
page.once('dialog',dialog=>dialog.accept());
await page.getByRole('button',{name:'Reset demo data'}).click();
await page.waitForURL(/#dashboard/);
state=await page.evaluate(()=>JSON.parse(localStorage.getItem('propertypilot:v1')));
if(state.properties.length!==5||state.template!=='residential')throw new Error('Reset did not restore the demo workspace');
if(errors.length)throw new Error('Browser page errors: '+errors.join(' | '));
console.log(JSON.stringify({ok:true,templateSelection:true,sampleProperty:true,purposeAwareCopy:true,localStatusWorkflow:true,generation:true,textExport:txt.suggestedFilename(),jsonExport:json.suggestedFilename(),reset:true}));
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
